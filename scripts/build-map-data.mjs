// Regenerates src/data/usMap.ts and src/data/geo.ts from the bundled US Census
// state topology (us-atlas states-10m, public domain). Only needs running if the
// boundaries or the simplification thresholds change:
//
//   npx --yes -p d3-geo -p topojson-client -p topojson-simplify node scripts/build-map-data.mjs
//
// Emits:
//   src/data/usMap.ts  – Albers USA SVG paths for the board
//   src/data/geo.ts    – coarse lat/lon rings + neighbour lists for "Nearby"
import fs from "node:fs";
import { geoAlbersUsa, geoPath } from "d3-geo";
import { feature, neighbors } from "topojson-client";
import { presimplify, simplify, filter, filterAttachedWeight, filterWeight } from "topojson-simplify";

const FIPS = {
  "01": "AL", "02": "AK", "04": "AZ", "05": "AR", "06": "CA", "08": "CO", "09": "CT",
  "10": "DE", "11": "DC", "12": "FL", "13": "GA", "15": "HI", "16": "ID", "17": "IL",
  "18": "IN", "19": "IA", "20": "KS", "21": "KY", "22": "LA", "23": "ME", "24": "MD",
  "25": "MA", "26": "MI", "27": "MN", "28": "MS", "29": "MO", "30": "MT", "31": "NE",
  "32": "NV", "33": "NH", "34": "NJ", "35": "NM", "36": "NY", "37": "NC", "38": "ND",
  "39": "OH", "40": "OK", "41": "OR", "42": "PA", "44": "RI", "45": "SC", "46": "SD",
  "47": "TN", "48": "TX", "49": "UT", "50": "VT", "51": "VA", "53": "WA", "54": "WV",
  "55": "WI", "56": "WY"
};
const OUT = new URL("../src/data/", import.meta.url).pathname;
const raw = () => JSON.parse(fs.readFileSync(new URL("./states-10m.json", import.meta.url), "utf8"));
const round = (d, p = 10) => d.replace(/-?\d+\.?\d*/g, (n) => String(Math.round(Number(n) * p) / p));
const dropDegenerate = (d) =>
  d.split("Z").filter(Boolean)
    .filter((r) => new Set(r.match(/-?\d+\.?\d*,-?\d+\.?\d*/g) || []).size >= 3)
    .join("Z") + "Z";

function simplified(weight, ring) {
  let t = presimplify(raw());
  t = simplify(t, weight);
  return filter(t, filterAttachedWeight(t, ring, filterWeight));
}

/* ---------- 1. the board: Albers USA, 1000 x 560 ---------- */
{
  const topo = simplified(0.005, 0.06);
  const feats = feature(topo, topo.objects.states).features.filter((f) => FIPS[f.id]);
  const projection = geoAlbersUsa().fitExtent([[8, 8], [848, 552]], { type: "FeatureCollection", features: feats });
  const path = geoPath(projection);
  const paths = {};
  for (const f of feats) paths[FIPS[f.id]] = dropDegenerate(round(path(f)));

  // Alaska borders nothing, so it can be simplified far harder without seams
  const akTopo = simplified(0.06, 1.5);
  const ak = feature(akTopo, akTopo.objects.states).features.find((f) => f.id === "02");
  paths.AK = dropDegenerate(round(geoPath(projection)(ak)));

  const entries = Object.keys(paths).sort().map((k) => `  ${k}: ${JSON.stringify(paths[k])}`).join(",\n");
  fs.writeFileSync(OUT + "usMap.ts",
`// GENERATED by scripts/build-map-data.mjs — do not edit by hand.
// US Census state boundaries (us-atlas / TIGER), topology-simplified so shared
// borders stay stitched, then projected with d3-geo's Albers USA so Alaska and
// Hawaii sit in their conventional insets.
export const MAP_VIEWBOX = { width: 1000, height: 560 } as const;

export const STATE_PATHS: Record<string, string> = {
${entries}
};
`);
  console.log("usMap.ts", (fs.statSync(OUT + "usMap.ts").size / 1024).toFixed(1), "KB");
}

/* ---------- 2. nearby: coarse lat/lon rings + adjacency ---------- */
{
  const topo = simplified(0.015, 2.5);
  const all = feature(topo, topo.objects.states).features;
  const geoms = topo.objects.states.geometries;
  const nb = neighbors(geoms);

  const adjacency = {};
  geoms.forEach((g, i) => {
    const code = FIPS[g.id];
    if (!code) return;
    adjacency[code] = nb[i].map((j) => FIPS[geoms[j].id]).filter(Boolean).sort();
  });
  // the topology has no arc between DC and Virginia across the Potomac, and
  // island states share no border at all — both matter for "what's near me"
  const EXTRA = { DC: ["VA", "MD"], VA: ["DC"], MD: ["DC"], HI: [], AK: [] };
  for (const [code, add] of Object.entries(EXTRA)) {
    adjacency[code] = [...new Set([...(adjacency[code] || []), ...add])].sort();
  }

  // D.C. is small enough that the shared simplification erodes it away
  // entirely — take its outline from the raw topology instead.
  const fineDC = feature(raw(), raw().objects.states).features.find((f) => f.id === "11");

  const rings = {};
  for (const f of [...all, fineDC]) {
    const code = FIPS[f.id];
    if (!code) continue;
    const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
    const out = [];
    for (const poly of polys) {
      const outer = poly[0].map(([x, y]) => [Math.round(x * 100) / 100, Math.round(y * 100) / 100]);
      if (outer.length >= 4) out.push(outer.flat());
    }
    rings[code] = out;
  }

  const ringEntries = Object.keys(rings).sort()
    .map((k) => `  ${k}: [${rings[k].map((r) => `[${r.join(",")}]`).join(",")}]`).join(",\n");
  const adjEntries = Object.keys(adjacency).sort()
    .map((k) => `  ${k}: [${adjacency[k].map((c) => `"${c}"`).join(", ")}]`).join(",\n");

  fs.writeFileSync(OUT + "geo.ts",
`// GENERATED by scripts/build-map-data.mjs — do not edit by hand.
// Coarse lon/lat outlines (flat [lon, lat, lon, lat, ...] per ring) and the
// shared-border adjacency list, both derived from the same Census topology as
// usMap.ts. Deliberately low resolution: this only has to answer "which state
// am I in, and what borders it", and it has to do it with no network.
export const STATE_RINGS: Record<string, number[][]> = {
${ringEntries}
};

export const STATE_NEIGHBORS: Record<string, string[]> = {
${adjEntries}
};
`);
  console.log("geo.ts", (fs.statSync(OUT + "geo.ts").size / 1024).toFixed(1), "KB");
  console.log("sample adjacency — CO:", adjacency.CO.join(","), "| TX:", adjacency.TX.join(","), "| ME:", adjacency.ME.join(","));
}
